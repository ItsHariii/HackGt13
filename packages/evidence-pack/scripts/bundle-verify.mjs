// Bundles src/cli.ts into the single-file verify.mjs every Evidence Pack carries (TASKS T15.2),
// then stores it as a string in src/verify-script.generated.ts so the web app can zip it.
//   node scripts/bundle-verify.mjs          regenerate
//   node scripts/bundle-verify.mjs --check  fail when the committed bundle is stale
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src/verify-script.generated.ts");

export async function bundle() {
  const result = await build({
    entryPoints: [join(root, "src/cli.ts")],
    // Source-path comments are relative to this, so the output is the same from any cwd.
    absWorkingDir: root,
    bundle: true,
    write: false,
    platform: "node",
    format: "esm",
    target: "node20",
    // Readable on purpose: anyone should be able to audit what they run.
    minify: false,
    legalComments: "inline",
    charset: "utf8",
    banner: {
      js: [
        "// verify.mjs: re-verifies a Cartel Evidence Pack offline.",
        "// Run `node verify.mjs` in the unzipped pack. No network, no dependencies.",
        "// Generated from packages/evidence-pack/src/cli.ts.",
      ].join("\n"),
    },
    logLevel: "silent",
  });
  const code = result.outputFiles[0].text;
  // Keep absolute build paths out of the bundle so it is the same on every machine.
  return code.replaceAll(`${root}/`, "").replaceAll(root, ".");
}

export function moduleSource(code) {
  return [
    "// Generated by scripts/bundle-verify.mjs. Do not edit; run `pnpm --filter @cartel/evidence-pack verify:bundle`.",
    `export const VERIFY_MJS: string = ${JSON.stringify(code)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = moduleSource(await bundle());
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== next) {
      console.error(
        "verify.mjs bundle is stale: run `pnpm --filter @cartel/evidence-pack verify:bundle`.",
      );
      process.exit(1);
    }
    console.log("verify.mjs bundle is up to date.");
  } else {
    writeFileSync(OUT, next);
    console.log(`Wrote ${OUT} (${next.length} bytes).`);
  }
}
